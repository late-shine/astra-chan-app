/** Regression checks for QZ10's bounded public-factory caches and foil interning. */
import assert from 'node:assert/strict';
import {createKanaCandidates} from '../src/quiz/content/kana';
import {finishFactory,uniqueFoils} from '../src/quiz/distractors';
import {buildQuestions} from '../src/quiz/pool';
import {seededRandom} from '../src/quiz/random';
import {HIRAGANA_DATA,KATAKANA_DATA} from '../src/data';
import type {Catalogs,BuildConfig} from '../src/quiz/types';
let passed=0;
const check=(name:string,value:unknown)=>{assert.ok(value,name);passed++;};
const foils=[{label:'Answer',score:99},{label:'Ａlpha',score:1},{label:'Alpha',score:2},{label:'Beta',score:1},{label:'gamma',score:4}];
check('dedupe keeps canonical ordering and strongest normalized label',JSON.stringify(uniqueFoils(foils,[' answer ']))===JSON.stringify([{label:'Alpha',score:2},{label:'Beta',score:1},{label:'gamma',score:4}]));
const catalogs:Catalogs={hiragana:HIRAGANA_DATA,katakana:KATAKANA_DATA,kanji:[],vocabulary:[]};
const base=createKanaCandidates(catalogs).candidates[0];
const input={...base,answers:['Answer'],foils};
const output=finishFactory(1,[input,{...input}],[]);
check('factory output is deeply immutable',Object.isFrozen(output.candidates[0].foils)&&Object.isFrozen(output.candidates[0].foils[0]));
check('interned output never freezes caller objects',!Object.isFrozen(input)&&!Object.isFrozen(foils)&&foils.every(f=>!Object.isFrozen(f)));
check('repeated immutable label-score pairs share output storage',output.candidates[0].foils[0]===output.candidates[1].foils[0]);
foils[1].label='Changed';foils[2].score=900;
check('later caller mutation cannot change frozen output',output.candidates[0].foils[0].label==='Alpha'&&output.candidates[0].foils[0].score===2);
const config:BuildConfig={subject:'kana',sessionId:'cache-probe',now:0,length:10,kinds:['kana-read'],choiceCount:4,pool:{script:'hiragana',stages:['basic']}};
const source=catalogs.hiragana.map(row=>({...row}));const mutable={...catalogs,hiragana:source};
const round=()=>buildQuestions(mutable,config,{},seededRandom(123)).questions;
check('warm cache preserves deterministic order/choices',JSON.stringify(round())===JSON.stringify(round()));
const glyph=source[0].kana;source[0].romaji='customreading';
const changed=buildQuestions(mutable,{...config,length:100},{},seededRandom(123)).questions.find(q=>q.face===glyph);
check('in-place kana source edits invalidate cache',changed?.reveal.answer==='customreading');
const katakana=KATAKANA_DATA.map(row=>({...row}));const both={...mutable,katakana};
const kataConfig={...config,pool:{script:'katakana' as const,stages:['basic' as const]},length:100};
buildQuestions(both,kataConfig,{},seededRandom(1));katakana[0].romaji='katacustom';
check('katakana dependency also invalidates cache',buildQuestions(both,kataConfig,{},seededRandom(1)).questions.find(q=>q.face===katakana[0].kana)?.reveal.answer==='katacustom');
check('cache never widens target script',round().every(q=>source.some(row=>row.kana===q.face)));
console.log(`${passed} performance regression checks passed; 0 failed. No wall-clock threshold or device-speed claim.`);
